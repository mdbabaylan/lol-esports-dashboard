// Helper function to get H2H history between two teams
export const getH2HHistory = (teamAName, teamBName) => {
  return matches.filter(
    (match) =>
      match.status === 'completed' &&
      ((match.teamA.name === teamAName && match.teamB.name === teamBName) ||
        (match.teamA.name === teamBName && match.teamB.name === teamAName))
  )
}

// Helper function to get team by name
export const getTeamByName = (teamName) => {
  return teams.find((team) => team.name === teamName)
}

// Helper function to get player by name
export const getPlayerByName = (playerName) => {
  return players.find((player) => player.name.toLowerCase() === playerName.toLowerCase())
}

// Helper function to filter players by role
export const getPlayersByRole = (role) => {
  return players.filter((player) => player.role === role)
}

// Helper function to get matches by event
export const getMatchesByEvent = (event) => {
  return matches.filter((match) => match.event === event)
}

// Helper function to calculate bet statistics
export const getBetStats = () => {
  const settledBets = bets.filter((bet) => bet.result !== 'pending')
  const totalBets = settledBets.length
  const wins = settledBets.filter((bet) => bet.result === 'win').length
  const losses = settledBets.filter((bet) => bet.result === 'loss').length
  const winRate = totalBets > 0 ? (wins / totalBets) * 100 : 0
  const totalProfit = settledBets.reduce((sum, bet) => sum + (bet.profit || 0), 0)
  const totalStaked = settledBets.reduce((sum, bet) => sum + bet.stake, 0)
  const roi = totalStaked > 0 ? (totalProfit / totalStaked) * 100 : 0

  return {
    totalBets,
    wins,
    losses,
    winRate: winRate.toFixed(1),
    totalProfit: totalProfit.toFixed(2),
    totalStaked: totalStaked.toFixed(2),
    roi: roi.toFixed(1),
  }
}
